library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity dmx_1to4 is
    Port ( 
        X   : in  STD_LOGIC;                     -- ???? ??????
        a   : in  STD_LOGIC_VECTOR(1 downto 0);  -- ???????? ????? (a1, a0)
        E   : in  STD_LOGIC;                     -- ???? ?????????? (Enable)
        F   : out STD_LOGIC_VECTOR(3 downto 0)   -- ?????? (F0, F1, F2, F3)
    );
end dmx_1to4;

architecture Behavioral of dmx_1to4 is
begin
    process(X, a, E)
    begin
        if E = '1' then
            -- ?????????? ??? ??????
            F <= (others => '0');
            
            -- ?????????? ?????? ????? ? ??????????? ?? ??????
            case a is
                when "00"   => F(0) <= X;  -- F0 = X
                when "01"   => F(1) <= X;  -- F1 = X
                when "10"   => F(2) <= X;  -- F2 = X
                when "11"   => F(3) <= X;  -- F3 = X
                when others => F <= (others => '0');
            end case;
        else
            -- ??? E=0 ??? ?????? ?????????????
            F <= (others => '0');
        end if;
    end process;
end Behavioral;