library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity dmx_1to4 is
    Port ( 
        a   : in  STD_LOGIC_VECTOR(1 downto 0);  -- ???????? ????? (a1, a0)
        E   : in  STD_LOGIC;                     -- ??????????????/??????????? ???? (Enable)
        F   : out STD_LOGIC_VECTOR(3 downto 0)   -- ?????? (F3, F2, F1, F0)
    );
end dmx_1to4;

architecture Behavioral of dmx_1to4 is
begin
    process(E, a)
    begin
        -- ?? ????????? ?? ???? ??????? ????
        F <= (others => '0'); 
        
        -- ???? E = 1, ???????? ?????? ????? ?? ??????
        if E = '1' then
            case a is
                when "00"   => F(0) <= '1';  -- F0 = 1
                when "01"   => F(1) <= '1';  -- F1 = 1
                when "10"   => F(2) <= '1';  -- F2 = 1
                when "11"   => F(3) <= '1';  -- F3 = 1
                when others => F <= (others => '0');
            end case;
        end if;
    end process;
end Behavioral;