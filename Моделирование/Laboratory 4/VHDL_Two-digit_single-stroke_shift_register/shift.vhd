library IEEE;
use IEEE.std_logic_1164.all;

entity shift is
    port (
        D  : in  std_logic;
        C  : in  std_logic;
        R  : in  std_logic;
        D1 : out std_logic;
        Q1 : out std_logic;
        D2 : out std_logic;
        Q2 : out std_logic
    );
end shift;

architecture beh of shift is
    -- ?????????? ??????? ?????????????, ????? ?? ????????????? ? ??????? Q1, Q2
    signal s1, s2, s3, s4 : std_logic := '0';
begin
    -- ?????? ????: ????????, ??????????? ?? ?????? C (DFF1 ? DFF2)
    process (C, R)
    begin
        if R = '0' then
            s1 <= '0';
            s2 <= '0';
        elsif rising_edge(C) then
            s1 <= D;
            s2 <= s1;
        end if;
    end process;

    -- ?????? ????: ????????, ??????????? ?? ????? C (DFF3 ? DFF4)
    process (C, R)
    begin
        if R = '0' then
            s3 <= '0';
            s4 <= '0';
        elsif falling_edge(C) then
            s3 <= s2;
            s4 <= s3;
        end if;
    end process;

    -- ?????????? ??????? ? ???????????? ?? ??????
    D1 <= s1;
    Q1 <= s2;
    D2 <= s3;
    Q2 <= s4;
end beh;