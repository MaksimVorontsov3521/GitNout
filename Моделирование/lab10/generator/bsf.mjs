// Authentic Quartus II .bsf / in-sheet symbol templates for project-owned entities.
// Geometry rules reverse-engineered from CMP_2bit.bsf and encoder_8-3.bsf:
//   outer rect      (16,16) .. (16+W, 16+H)
//   inner box       (16,16) .. (W-16, H-16)
//   input ports     x = 0,   y = 32 + 16k,  stub line to (16,y)
//   output ports    x = W,   y = 32 + 16k,  stub line to (W-16,y)
//   H = 16*max(nIn,nOut) + 48
//   name text       (rect 5 0 tw 14)  font Arial 8
//   "inst" text     (rect 8 H-16 25 H-4) font Arial
const NL = String.fromCharCode(10);
const TAB = String.fromCharCode(9);

const WIDE = { A: 8, B: 8, C: 8, D: 8, E: 8, F: 8, G: 8, H: 8, I: 5, J: 7, K: 8, L: 7, M: 11, N: 8, O: 9, P: 8, Q: 9, R: 8, S: 8, T: 7, U: 8, V: 8, W: 12, X: 8, Y: 8, Z: 8 };
const LOWER = { a: 7, b: 8, c: 7, d: 8, e: 8, f: 5, g: 8, h: 8, i: 3, j: 4, k: 7, l: 3, m: 12, n: 8, o: 8, p: 8, q: 8, r: 5, s: 7, t: 5, u: 8, v: 7, w: 10, x: 7, y: 7, z: 7 };
const DIGIT = 8;
const PUNCT = { '[': 5, ']': 5, '.': 4, '_': 8, '-': 5, ':': 3, ',': 4, '(': 5, ')': 5, '0': DIGIT };

export function textWidth(s) {
  let w = 0;
  for (const ch of s) {
    if (ch >= 'A' && ch <= 'Z') w += WIDE[ch] || 8;
    else if (ch >= 'a' && ch <= 'z') w += LOWER[ch] || 7;
    else if (ch >= '0' && ch <= '9') w += DIGIT;
    else w += PUNCT[ch] != null ? PUNCT[ch] : 6;
  }
  return w;
}

export function symbolGeometry(inputs, outputs) {
  const nIn = inputs.length, nOut = outputs.length;
  const rows = Math.max(nIn, nOut, 1);
  const h = 16 * rows + 48;
  const longest = Math.max(...[...inputs, ...outputs].map((s) => textWidth(s)), 16);
  const w = longest + 48 > 96 ? 112 : 96;
  return { w, h };
}

function portNode(label, dir, idx, w) {
  const y = 32 + 16 * idx;
  const tw = textWidth(label);
  const t1 = '(text "' + label + '"(rect 0 0 ' + tw + ' 14)(font "Arial"(font_size 8)))';
  const t2 = dir === 'input'
    ? '(text "' + label + '"(rect 21 ' + (y - 5) + ' ' + (21 + tw) + ' ' + (y + 9) + ')(font "Arial"(font_size 8)))'
    : '(text "' + label + '"(rect ' + (w - 21 - tw) + ' ' + (y - 5) + ' ' + (w - 21) + ' ' + (y + 9) + ')(font "Arial"(font_size 8)))';
  const px = dir === 'input' ? 0 : w;
  const ex = dir === 'input' ? 16 : w - 16;
  return [
    TAB + '(port',
    TAB + TAB + '(pt ' + px + ' ' + y + ')',
    TAB + TAB + '(' + dir + ')',
    TAB + TAB + t1,
    TAB + TAB + t2,
    TAB + TAB + '(line (pt ' + px + ' ' + y + ')(pt ' + ex + ' ' + y + ')(line_width 1))',
    TAB + ')',
  ];
}

export function symbolNode(entity, inputs, outputs, x, y) {
  const g = symbolGeometry(inputs, outputs);
  const L = [];
  L.push('(symbol');
  L.push(TAB + '(rect ' + x + ' ' + y + ' ' + (x + g.w) + ' ' + (y + g.h) + ')');
  L.push(TAB + '(text "' + entity + '"(rect 5 0 ' + (5 + textWidth(entity)) + ' 14)(font "Arial"(font_size 8)))');
  L.push(TAB + '(text "inst"(rect 8 ' + (g.h - 16) + ' 25 ' + (g.h - 4) + ')(font "Arial"(font_size 8)))');
  inputs.forEach((p, i) => L.push(...portNode(p, 'input', i, g.w)));
  outputs.forEach((p, i) => L.push(...portNode(p, 'output', i, g.w)));
  L.push(TAB + '(drawing');
  L.push(TAB + TAB + '(rectangle (rect 16 16 ' + (g.w - 16) + ' ' + (g.h - 16) + ')(line_width 1))');
  L.push(TAB + ')');
  L.push(')');
  return { lines: L, w: g.w, h: g.h, ports: portMap(inputs, outputs, g.w) };
}

export function portMap(inputs, outputs, w) {
  const out = [];
  inputs.forEach((p, i) => out.push({ label: p, dir: 'input', dx: 0, dy: 32 + 16 * i }));
  outputs.forEach((p, i) => out.push({ label: p, dir: 'output', dx: w, dy: 32 + 16 * i }));
  return out;
}

