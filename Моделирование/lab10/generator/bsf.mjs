export function emitBsf(entity, inputs, outputs) {
  const L = [];
  L.push('/* Generated by the dsh Quartus bridge: project symbol file, no GUI interaction. */');
  L.push(...LEGAL);
  L.push('(header "symbol" (version "1.1"))');
  const s = symbolNode(entity, inputs, outputs, 16, 16);
  L.push(...s.lines);
  return L.join(NL) + NL;
}

export function templateFor(entity, inputs, outputs) {
  const s = symbolNode(entity, inputs, outputs, 0, 0);
  return { name: entity, w: s.w, h: s.h, ports: s.ports, lines: s.lines, user: true };
}
