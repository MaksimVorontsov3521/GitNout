// Generate Quartus II 5.0 Vector Waveform Files (.vwf) from a spec.
// Two authentic stimulus styles, matching the reference lab files:
//   * BUS + nested NODE/REPEAT counter  -> "Count Value" on a bus (VHDLCMP_4BIT.vwf)
//   * GROUP("name"){MEMBERS=...}       -> grouping of separate pins (CMP_2bit.vwf)
//   * explicit vectors                 -> "Arbitrary Value" over intervals
const NL = String.fromCharCode(10);
const TAB = String.fromCharCode(9);

function fmt(x) { return (Math.round(x * 1000) / 1000).toFixed(1); }

function collapse(steps) {
  const out = [];
  let cur = null, acc = 0;
  for (const s of steps) {
    if (cur === null) { cur = s.level; acc = s.dur; continue; }
    if (s.level === cur) { acc += s.dur; continue; }
    out.push({ level: cur, dur: acc });
    cur = s.level; acc = s.dur;
  }
  if (cur !== null) out.push({ level: cur, dur: acc });
  return out;
}

// bitOrder: members listed MSB first, as Quartus does for a bus
function counterSteps(bitIndexFromLsb, bits, period) {
  const dur = period * Math.pow(2, bitIndexFromLsb);
  const repeat = Math.pow(2, bits - 1 - bitIndexFromLsb);
  return { dur, repeat };
}

// A bus may be declared either by an explicit member list or by a range. Both spellings are
// reduced to bare bit names here, which is what the sheet draws on each branch wire.
export function busMembers(bd) {
  const bare = (m) => { const x = /^([A-Za-z0-9_]+)\[(\d+)\]$/.exec(m); return x ? x[1] + Number(x[2]) : m; };
  if (bd.members && bd.members.length) return bd.members.map(bare);
  const a = [];
  for (let i = bd.hi; i >= bd.lo; i--) a.push(bd.name + i);
  return a;
}
// A waveform channel that is one bit of a bus must be spelled NAME[i]: Quartus 5.0 binds the
// stimulus to the vector port that way, and a bare NAMEi channel is silently ignored, which
// leaves every wire behind the bus at 'X'. The sheet still labels the branch wire NAMEi,
// because that is what a BDF connector text carries.
const busChan = (bd, m) => {
  const x = new RegExp('^' + bd.name + '(\\d+)$').exec(m);
  return x ? bd.name + '[' + Number(x[1]) + ']' : m;
};
const normBuses = (spec) => ((spec.buses || []).map((bd) => {
  const members = busMembers(bd);
  return Object.assign({}, bd, { members, channels: members.map((m) => busChan(bd, m)) });
}));

export function expandRows(spec) {
  const inputs = flatChannels(spec);
  const n = inputs.length;
  if (spec.vectors) return spec.vectors;
  return Array.from({ length: 1 << n }, (_, i) => {
    const row = {};
    inputs.forEach((p, k) => { row[p] = (i >> (n - 1 - k)) & 1; });
    return row;
  });
}

// Every input channel of the design, in the spelling a .vwf must use.
export function flatChannels(spec) {
  const plain = spec.inputs || [];
  if (!spec.buses) return plain.slice();
  const out = [];
  // Only an input bus contributes stimulus; an output bus is observed, never driven.
  for (const b of normBuses(spec)) {
    if (((b.dir || 'input').toLowerCase()) !== 'input') continue;
    for (const c of b.channels) out.push(c);
  }
  return out.concat(plain);
}

export function emitVwf(spec, opts) {
  const o = opts || {};
  const period = Number(spec.period || o.period || 40);
  const plainIn = spec.inputs || [];
  const plainOut = spec.outputs || [];
  const buses = normBuses(spec);
  const groups = spec.groups || [];
  const rows = expandRows(spec);
  const total = rows.length * period;
  const vectorised = spec.vectors != null;
  const outSet = new Set(plainOut);

  // Unified signal registry. Every waveform channel is declared exactly once, with a
  // direction and a stimulus policy; an output channel is never given a stimulus list,
  // which is what makes Quartus treat it as a observed signal rather than a driven one.
  const chan = new Map();
  const declare = (name, dir, kind, parent) => {
    if (chan.has(name)) throw new Error('duplicate waveform channel ' + name);
    chan.set(name, { name, dir, kind, parent });
  };
  for (const b of buses) {
    const dir = (b.dir || 'INPUT').toUpperCase();
    declare(b.name, dir, 'BUS', null);
    for (const c of b.channels) declare(c, dir, 'BIT', b.name);
  }
  const covered = new Set([...buses.flatMap((b2) => b2.channels), ...groups.flatMap((g) => g.members)]);
  for (const g of groups) for (const m of g.members) declare(m, outSet.has(m) ? 'OUTPUT' : 'INPUT', 'BIT', null);
  for (const nm of plainIn) if (!covered.has(nm)) declare(nm, 'INPUT', 'BIT', null);
  for (const nm of plainOut) if (!covered.has(nm)) declare(nm, 'OUTPUT', 'BIT', null);

  const L = [];
  const push = (...xs) => xs.forEach((x) => L.push(x));
  push('/* Generated by the dsh Quartus bridge: host-authored vector file, no GUI interaction. */', '');
  push('HEADER', '{');
  push(TAB + 'VERSION = 1;');
  push(TAB + 'TIME_UNIT = ns;');
  push(TAB + 'SIMULATION_TIME = 0.0;');
  push(TAB + 'GRID_PHASE = 0.0;');
  push(TAB + 'GRID_PERIOD = ' + fmt(period) + ';');
  push(TAB + 'GRID_DUTY_CYCLE = 50;');
  push('}', '');

  for (const c of chan.values()) {
    push('SIGNAL("' + c.name + '")', '{');
    push(TAB + 'VALUE_TYPE = NINE_LEVEL_BIT;');
    push(TAB + 'SIGNAL_TYPE = ' + (c.kind === 'BUS' ? 'BUS' : 'SINGLE_BIT') + ';');
    if (c.kind === 'BUS') {
      const b = buses.find((x) => x.name === c.name);
      push(TAB + 'WIDTH = ' + b.members.length + ';');
      push(TAB + 'LSB_INDEX = 0;');
    } else {
      push(TAB + 'WIDTH = 1;');
      push(TAB + 'LSB_INDEX = -1;');
    }
    push(TAB + 'DIRECTION = ' + c.dir + ';');
    push(TAB + 'PARENT = "' + (c.parent || '') + '";');
    push('}', '');
  }
  for (const g of groups) {
    push('GROUP("' + g.name + '")', '{');
    push(TAB + 'MEMBERS = ' + g.members.map((m) => '"' + m + '"').join(', ') + ';');
    push('}', '');
  }

  const stimulus = (name, dir, bits, pos) => {
    push('TRANSITION_LIST("' + name + '")', '{', TAB + 'NODE', TAB + '{');
    push(TAB + TAB + 'REPEAT = 1;');
    if (dir === 'OUTPUT') { push(TAB + TAB + 'LEVEL X FOR ' + fmt(total) + ';'); push(TAB + '}', '}', ''); return; }
    if (vectorised) {
      const steps = rows.map((r) => ({ level: String(r[name] === undefined ? 0 : r[name]), dur: period }));
      for (const t of collapse(steps)) push(TAB + TAB + 'LEVEL ' + t.level + ' FOR ' + fmt(t.dur) + ';');
    } else {
      const cs = counterSteps(bits - 1 - pos, bits, period);
      push(TAB + TAB + 'NODE', TAB + TAB + '{');
      push(TAB + TAB + TAB + 'REPEAT = ' + cs.repeat + ';');
      push(TAB + TAB + TAB + 'LEVEL 0 FOR ' + fmt(cs.dur) + ';');
      push(TAB + TAB + TAB + 'LEVEL 1 FOR ' + fmt(cs.dur) + ';');
      push(TAB + TAB + '}');
    }
    push(TAB + '}', '}', '');
  };
  for (const b of buses) {
    const dir = (b.dir || 'INPUT').toUpperCase();
    b.channels.forEach((m, k) => stimulus(m, dir, b.channels.length, k));
  }
  for (const g of groups) {
    g.members.forEach((m, k) => stimulus(m, chan.get(m).dir, g.members.length, k));
  }
  for (const nm of plainIn) if (!covered.has(nm)) stimulus(nm, 'INPUT', 0, 0);
  for (const nm of plainOut) if (!covered.has(nm)) stimulus(nm, 'OUTPUT', 0, 0);

  let idx = 0;
  const lines = [];
  const add = (channel, level, parent, children, radix) => {
    const my = idx++;
    lines.push({ channel, level, parent, children, radix, my });
    return my;
  };
  for (const b of buses) {
    const start = idx + 1;
    const grp = add(b.name, 0, null, b.channels.map((_, k) => start + k), b.radix || 'Unsigned');
    for (const m of b.channels) add(m, 1, grp, null, b.radix || 'Unsigned');
  }
  for (const g of groups) {
    const start = idx + 1;
    const grp = add(g.name, 0, null, g.members.map((_, k) => start + k), g.radix || 'Unsigned');
    for (const m of g.members) add(m, 1, grp, null, g.radix || 'Binary');
  }
  for (const nm of plainIn) if (!covered.has(nm)) add(nm, 0, null, null, 'Binary');
  for (const nm of plainOut) if (!covered.has(nm)) add(nm, 0, null, null, 'Binary');
  for (const ln of lines) {
    push('DISPLAY_LINE', '{');
    push(TAB + 'CHANNEL = "' + ln.channel + '";');
    push(TAB + 'EXPAND_STATUS = COLLAPSED;');
    push(TAB + 'RADIX = ' + ln.radix + ';');
    push(TAB + 'TREE_INDEX = ' + ln.my + ';');
    push(TAB + 'TREE_LEVEL = ' + ln.level + ';');
    if (ln.parent !== null && ln.parent !== undefined) push(TAB + 'PARENT = ' + ln.parent + ';');
    if (ln.children && ln.children.length) push(TAB + 'CHILDREN = ' + ln.children.join(', ') + ';');
    push('}', '');
  }
  push('TIME_BAR', '{');
  push(TAB + 'TIME = 0;');
  push(TAB + 'MASTER = TRUE;');
  push('}', ';');
  return L.join(NL) + NL;
}