def plural(n, forms):
    v = abs(int(str(n).replace(" ", "").replace(",", "")))
    m10, m100 = v % 10, v % 100
    if 10 < m100 < 20: return forms[2]
    if m10 == 1: return forms[0]
    if 1 < m10 < 5: return forms[1]
    return forms[2]

