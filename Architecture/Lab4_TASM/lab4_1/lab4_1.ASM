DOSSEG
.MODEL TINY
.DATA
    ; Массив слов для демонстрации адресации к памяти
    Array DW 10, 20, 30, 40, 50, 60, 70, 80

.CODE
ORG 100h

start:
;==============================================================
; 1. РЕГИСТРОВАЯ АДРЕСАЦИЯ
;    Оба операнда — в регистрах процессора.
;    Адрес не вычисляется, обращение к регистрам самое быстрое.
;==============================================================
    mov  ax, 100h       ; загрузим исходные значения
    mov  bx, 00FFh
    add  ax, bx         ; AX = AX + BX  (регистровая)
                        ; Результат: AX = 01FFh

;==============================================================
; 2. КОСВЕННО-РЕГИСТРОВАЯ АДРЕСАЦИЯ
;    Адрес операнда хранится в регистре (BX).
;    Физ. адрес = DS*16 + BX
;==============================================================
    lea  bx, Array      ; BX = смещение начала массива
    add  ax, [bx]       ; AX = AX + Array[0]
                        ; Операнд берётся по адресу DS:BX

;==============================================================
; 3. БАЗОВАЯ (ИНДЕКСНАЯ) АДРЕСАЦИЯ
;    Адрес = содержимое регистра-базы/индекса + смещение (disp).
;    Здесь: BX + 4  (смещение в байтах, 4 = 2-й элемент DW)
;==============================================================
    add  ax, [bx+4]     ; AX = AX + Array[2]
                        ; Физ. адрес = DS*16 + BX + 4

;==============================================================
; 4. БАЗОВО-ИНДЕКСНАЯ АДРЕСАЦИЯ
;    Адрес = база (BX) + индекс (SI), без смещения.
;    Удобно для обхода двумерных структур.
;==============================================================
    mov  si, 6          ; индекс = 6 байт → 3-й элемент (DW)
    add  ax, [bx+si]    ; AX = AX + Array[3]
                        ; Физ. адрес = DS*16 + BX + SI

;==============================================================
; 5. БАЗОВО-ИНДЕКСНАЯ АДРЕСАЦИЯ СО СМЕЩЕНИЕМ
;    Адрес = база (BX) + индекс (SI) + disp.
;    Самый гибкий способ: три компоненты адреса.
;==============================================================
    add  ax, [bx+si+2]  ; AX = AX + Array[4]
                        ; Физ. адрес = DS*16 + BX + SI + 2

;==============================================================
; Выход в DOS
;==============================================================
    mov  ah, 4Ch
    int  21h

END start